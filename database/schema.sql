-- Database 'postgres' sudah otomatis dibuat saat project Supabase dibuat.
-- Script ini hanya membuat tabel antrean.

CREATE TABLE IF NOT EXISTS public.antrean (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue_number INTEGER NOT NULL,
    nama VARCHAR(100) NOT NULL,
    keperluan VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'waiting'
        CHECK (status IN ('waiting', 'called', 'done')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    service_date DATE NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (service_date, queue_number)
);

CREATE INDEX IF NOT EXISTS idx_antrean_service_date_status
ON public.antrean (service_date, status, queue_number);
